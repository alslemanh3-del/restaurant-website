def seed():
    init_db()
    db = get_db()
    try:
        # التصنيفات (إدراج فقط إن كان الجدول فارغًا)
        count_cat = db.execute("SELECT COUNT(*) FROM categories").fetchone()[0]
        if count_cat == 0:
            for c in CATEGORIES:
                db.execute(
                    "INSERT INTO categories (key, label, sort_order) VALUES (?, ?, ?)",
                    c,
                )
            print(f"✓ أُدخلت {len(CATEGORIES)} تصنيفًا")
        else:
            print(f"• التصنيفات موجودة بالفعل ({count_cat})")

        # الأطباق
        count_d = db.execute("SELECT COUNT(*) FROM dishes").fetchone()[0]
        if count_d == 0:
            for d in DISHES:
                db.execute(
                    "INSERT INTO dishes (name, category_key, description, price, rating, image) "
                    "VALUES (?, ?, ?, ?, ?, ?)",
                    d,
                )
            print(f"✓ أُدخلت {len(DISHES)} طبقًا")
        else:
            print(f"• الأطباق موجودة بالفعل ({count_d})")

        db.commit()
        print("✓ اكتملت عملية التعبئة (seed).")
    finally:
        db.close()


if __name__ == "__main__":
    seed()
